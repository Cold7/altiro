"""Human lung cancer: PC-9 empty vector (group A, osimertinib-sensitive) vs PC-9 TP53 R248Q
(group B, gain-of-function mutant with early osimertinib resistance), DMSO vs osimertinib 24 h.

Data: GEO GSE232890, raw counts generated by NCBI (no alignment needed). 2 replicates per group.
Requires: pip install "orthoresponse[all]"
Run from this folder:  python run_python.py
"""

import gzip
import urllib.request
from pathlib import Path

import pandas as pd

import orthoresponse as orr
from orthoresponse.plotting import plot_model_patterns

HERE = Path(__file__).parent
DATA = HERE / "data"
COUNTS_URL = ("https://www.ncbi.nlm.nih.gov/geo/download/?type=rnaseq_counts&acc=GSE232890"
              "&format=file&file=GSE232890_raw_counts_GRCh38.p13_NCBI.tsv.gz")
GENE_INFO_URL = "https://ftp.ncbi.nlm.nih.gov/gene/DATA/GENE_INFO/Mammalia/Homo_sapiens.gene_info.gz"


def fetch(url, dest):
    DATA.mkdir(exist_ok=True)
    if not dest.exists():
        print("Downloading", url)
        urllib.request.urlretrieve(url, dest)
    with open(dest, "rb") as fh:
        if fh.read(2) != b"\x1f\x8b":
            dest.unlink()
            raise RuntimeError(
                f"{url} did not return a gzip file (NCBI sometimes asks for a browser check). "
                f"Download it with a web browser and save it as {dest}.")
    return dest


def main():
    counts = pd.read_csv(fetch(COUNTS_URL, DATA / "GSE232890_raw_counts_GRCh38.p13_NCBI.tsv.gz"),
                         sep="\t", index_col=0)
    samples = pd.read_csv(HERE / "samples.tsv", sep="\t", index_col=0)
    with gzip.open(fetch(GENE_INFO_URL, DATA / "Homo_sapiens.gene_info.gz"), "rt") as fh:
        info = pd.read_csv(fh, sep="\t", usecols=["GeneID", "Symbol"], index_col=0)

    res = orr.run_orthoresponse(
        counts, samples,
        group_col="line", condition_col="treatment",
        group_a="EV", group_b="R248Q",             # A = sensitive, B = resistant
        control="DMSO", stress="Osimertinib",
    )
    res.classification.insert(0, "symbol", info["Symbol"].reindex(res.classification.index.astype(int)).values)
    out = res.save(HERE / "results_python")

    print(res.summary.to_string(index=False, float_format=lambda x: f"{x:.1f}"))
    print("\nStress-ready asymmetry among single-group responders:")
    print(res.asymmetry.to_string(index=False))

    # Genes the resistant line expresses constitutively at the drug-induced level of the sensitive line
    sr3 = res.classification.query("label == 'stress_ready_3'")
    top = sr3.sort_values("a_response_log2FoldChange", ascending=False).head(20)
    print("\nTop stress_ready_3 genes (induced by osimertinib in EV, constitutive in R248Q):")
    print(top[["symbol", "a_response_log2FoldChange", "basal_log2FoldChange"]].to_string())
    top.to_csv(out / "top_stress_ready_3.tsv", sep="\t")

    fig = plot_model_patterns(res.classification, condition_labels=("DMSO", "Osi"))
    fig.savefig(out / "model_patterns.png", dpi=150)
    print(f"\nResults in {out}/")


if __name__ == "__main__":
    main()
